// Раскладка повторов упражнения: для каждого повтора — подсказка, направление,
// целевая сторона ('both' | 'r' | 'l').
// nameOf переводит сторону точек в анатомическую сторону для подсказки
// (отличается, только если в настройках стороны поменяны местами).
export function planReps(ex, reps, affected, nameOf = (s) => s) {
  const healthy = affected === 'r' ? 'l' : 'r';
  const out = [];
  if (ex.sequence && !ex.alternateRepeat) {
    for (const step of ex.sequence) out.push({ cue: step.cue, dir: step.dir || ex.dir, target: 'both' });
    return out;
  }
  if (ex.sequence && ex.alternateRepeat) {
    for (let i = 0; i < reps; i++) {
      const step = ex.sequence[i % ex.sequence.length];
      out.push({ cue: step.cue, dir: ex.dir, target: 'both' });
    }
    return out;
  }
  if (ex.alternate) {
    // Сначала здоровая сторона — чтобы «вспомнить» движение, затем поражённая.
    // Пар повторов — половина от настройки (иначе упражнение идёт вдвое дольше остальных).
    for (let i = 0; i < Math.ceil(reps / 2); i++) {
      for (const s of [healthy, affected]) out.push({ cue: ex.cueFor(nameOf(s)), dir: ex.dir, target: s });
    }
    return out;
  }
  for (let i = 0; i < reps; i++) out.push({ cue: ex.cue, dir: ex.dir, target: 'both' });
  return out;
}
